"""Конфигурации маршрутов."""

from dataclasses import dataclass


@dataclass
class RoutePoint:
    """Точка маршрута."""
    id: str
    order: int
    name: str
    short: str
    caption: str
    description: str
    hint: str
    geo: tuple[float, float]
    foto: str = ""

@dataclass
class Route:
    id: str
    title: str
    description: str
    cover_image: str
    map_image: str
    map_bounds: tuple[float, float, float, float]
    points: list[RoutePoint]

    @property
    def points_count(self) -> int:
        return len(self.points)

    def with_points(self, points: list[RoutePoint]) -> "Route":
        """Копия маршрута с другим набором точек (для частичного прохождения)."""
        return Route(
            id=self.id,
            title=self.title,
            description=self.description,
            cover_image=self.cover_image,
            map_image=self.map_image,
            map_bounds=self.map_bounds,
            points=points,
        )


